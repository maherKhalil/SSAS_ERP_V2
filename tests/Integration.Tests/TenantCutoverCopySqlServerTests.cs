  private sealed class ProbeContext : DbContext
  {
    protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder) =>
      optionsBuilder.UseSqlServer("Server=model-only;Database=model-only;Integrated Security=True");

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
      modelBuilder.Entity<ProbeParent>(entity =>
      {
        entity.ToTable("ProbeParents", "tenant");
        entity.HasKey(parent => parent.ProbeParentId);
        entity.Property(parent => parent.ProbeParentId).UseIdentityColumn();
        entity.Property(parent => parent.Label).HasMaxLength(64);
      });

      modelBuilder.Entity<ProbeChild>(entity =>
      {
        entity.ToTable("ProbeChildren", "tenant");
        entity.HasKey(child => child.ProbeChildId);
        entity.Property(child => child.Label).HasMaxLength(64);
        entity.HasOne<ProbeParent>()
          .WithMany()
          .HasForeignKey(child => child.ProbeParentId);
      });
    }

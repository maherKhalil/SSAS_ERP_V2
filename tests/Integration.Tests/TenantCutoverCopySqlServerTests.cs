  // ---- J. THE RACE E1 COULD NOT SEE. A release must not be able to unfreeze the source under a copy.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task A_freeze_cannot_be_released_while_a_copy_owns_the_operation()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await fixture.SeedCompaniesAsync(fixture.TenantA, 3, "REL");
    var operationId = await fixture.BeginAndFreezeAsync();

    // A copy is executing: it owns the operation.
    await using var copyOwner = new SqlConnection(fixture.PlatformConnectionString);
    await copyOwner.OpenAsync();
    Assert.True(await TenantCutoverOperationLock.TryAcquireForSessionAsync(
      copyOwner, operationId, TimeSpan.FromSeconds(5)));

    var released = await fixture.FreezeService().ReleaseFreezeAsync(operationId, "operator changed mind");

    // REFUSED, NOT DELAYED. Unfreezing here would let source writes resume while the copy is still reading.
    Assert.True(released.IsFailure);
    Assert.Equal(TenantStorageErrors.CutoverReleaseBlockedByActiveCopy.Code, released.Error.Code);

    // The durable state is untouched, so the source is still frozen...
    Assert.Equal(TenantCutoverOperationStatus.Frozen, (await fixture.ReadAsync(operationId)).Status);

    // ---- P. ...and a tenant write is still refused while the copy holds the operation.
    await using (var writer = fixture.SourceTenantContext(fixture.TenantA))
    {
      writer.Companies.Add(CopyFixture.NewCompany(fixture.TenantA, "DURING"));
      var refused = await Assert.ThrowsAsync<TenantStorageUnavailableException>(
        () => writer.SaveChangesAsync());
      Assert.Equal(TenantStorageErrors.TenantWritesFrozen.Code, refused.Error.Code);
    }

    // ---- Q. The co-tenant on the same shared database is unaffected throughout.
    await using (var coTenant = fixture.SourceTenantContext(fixture.TenantB))
    {
      coTenant.Companies.Add(CopyFixture.NewCompany(fixture.TenantB, "OTHER"));
      Assert.Equal(1, await coTenant.SaveChangesAsync());
    }

    // Once the copy's connection is gone, release works normally — a tenant is never permanently frozen.
    await copyOwner.CloseAsync();
    Assert.True((await fixture.FreezeService().ReleaseFreezeAsync(operationId, "done")).IsSuccess);
  }

  // ---- B + E. Identity preservation and foreign-key ordering, proven on real tables.
  //
  // No tenant entity uses an identity key or a foreign key TODAY, so these mechanisms would otherwise be
  // asserted only in the abstract. The probe model exercises the SAME plan derivation and the SAME copier
  // the engine uses, against real tables with a real FK and a real IDENTITY column.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task Identity_keys_and_foreign_key_order_survive_a_real_copy()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await CopyFixture.CreateProbeTablesAsync(fixture.SourceCatalog);
    await CopyFixture.CreateProbeTablesAsync(fixture.TargetCatalog);
    await fixture.SeedProbeDataAsync(fixture.TenantA);
    await fixture.SeedProbeDataAsync(fixture.TenantB);

    await using var probe = new ProbeContext();
    var plan = TenantCutoverCopyPlan.Build(probe.Model);
    Assert.True(plan.IsSuccess);

    // PRINCIPALS BEFORE DEPENDENTS. Derived from the model's foreign keys, not from table names — the
    // dependent sorts alphabetically first, so an alphabetical order would insert it before its parent.
    Assert.Equal(
      [nameof(ProbeParent), nameof(ProbeChild)],
      plan.Value.Select(table => table.EntityName).ToArray());
    Assert.True(Assert.Single(plan.Value, table => table.EntityName == nameof(ProbeParent)).HasIdentityColumn);

    var options = new TenantCutoverCopyOptions();
    var copier = new TenantCutoverTableCopier(options);
    var validator = new TenantCutoverCopyValidator(options);

    await using var source = new SqlConnection(CopyFixture.ConnectionFor(fixture.SourceCatalog));
    await using var target = new SqlConnection(CopyFixture.ConnectionFor(fixture.TargetCatalog));
    await source.OpenAsync();
    await target.OpenAsync();

    foreach (var table in plan.Value)
    {
      await using var transaction = (SqlTransaction)await target.BeginTransactionAsync();
      await copier.CopyAsync(table, fixture.TenantA, source, target, transaction);
      var validation = await validator.ValidateAsync(table, fixture.TenantA, source, target, transaction);
      Assert.True(validation.IsExact, validation.Difference);
      await transaction.CommitAsync();
    }

    // IDENTITY VALUES ARE THE SAME ON BOTH SIDES, which is what makes the child's foreign key still point at
    // the row it pointed at before the move.
    var sourceParents = await CopyFixture.ProbeParentIdsAsync(fixture.SourceCatalog, fixture.TenantA);
    var targetParents = await CopyFixture.ProbeParentIdsAsync(fixture.TargetCatalog, fixture.TenantA);
    Assert.Equal(sourceParents, targetParents);
    Assert.NotEmpty(targetParents);

    // The children arrived, their FK survived enforcement (CheckConstraints is on), and the co-tenant's
    // rows did not travel.
    Assert.Equal(4, await CopyFixture.ProbeChildCountAsync(fixture.TargetCatalog, fixture.TenantA));
    Assert.Equal(0, await CopyFixture.ProbeChildCountAsync(fixture.TargetCatalog, fixture.TenantB));
    Assert.Equal(0, await CopyFixture.OrphanedProbeChildCountAsync(fixture.TargetCatalog));
  }

  // ---- آ§18 performance, and آ§14 / LOW-3 plan measurement, at meaningful volume.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task A_large_tenant_copies_by_streaming_and_every_query_seeks()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    const int rows = 20_000;
    await fixture.SeedCompaniesAsync(fixture.TenantA, rows, "PERF");
    await fixture.SeedCompaniesAsync(fixture.TenantB, 5_000, "NOISE");
    var operationId = await fixture.BeginAndFreezeAsync();

    // Cutover history, so the E1 write-fence lookup is measured against an accumulated table rather than a
    // one-row fixture (LOW-3).
    await fixture.SeedCutoverHistoryAsync(5_000);
    await fixture.RefreshStatisticsAsync();

    var before = GC.GetTotalAllocatedBytes();
    var stopwatch = Stopwatch.StartNew();
    var copied = await fixture.CopyService().CopyAsync(operationId);
    stopwatch.Stop();
    var allocated = GC.GetTotalAllocatedBytes() - before;

    Assert.True(copied.IsSuccess);
    Assert.Equal(rows, copied.Value.TotalRows);
    Assert.Equal(rows, await fixture.TargetCompanyCountAsync(fixture.TenantA));
    Assert.Equal(0, await fixture.TargetCompanyCountAsync(fixture.TenantB));

    var perSecond = rows / Math.Max(stopwatch.Elapsed.TotalSeconds, 0.001);
    output.WriteLine(
      $"Copied+validated {rows} rows (co-tenant noise 5000) in {stopwatch.ElapsedMilliseconds}ms " +
      $"= {perSecond:F0} rows/sec, batch size {new TenantCutoverCopyOptions().BatchSize}, " +
      $"allocated {allocated / 1024 / 1024}MB ({(double)allocated / rows:F0} bytes/row).");

    // STREAMING, NOT MATERIALISED. Copy and validation each walk both sides once; a design that loaded the
    // tenant into memory would allocate on the order of the row payload times the row count.
    Assert.True(
      allocated < 256L * 1024 * 1024,
      $"copy allocated {allocated / 1024 / 1024}MB for {rows} rows, which is not streaming behaviour");

    // Issue both shapes through the real components, which records the exact statements production sends.
    // The plans are then taken from the server by replaying those statements, so nothing here depends on
    // what the plan cache still happens to remember.
    await fixture.ReissueMeasuredQueriesAsync();

    var plans = await fixture.CapturePlansAsync();
    Assert.True(
      plans.Count == 2,
      $"expected both reviewed query plans, captured: {string.Join(", ", plans.Select(plan => plan.Label))}");

    // The source read, and the E1 write-fence lookup (LOW-3), from the server's own plans.
    foreach (var measured in plans)
    {
      output.WriteLine(
        $"{measured.Label}: {measured.Operation} on {measured.Index}, " +
        $"{measured.LogicalReadsPerExecution} logical reads/execution, " +
        $"{measured.MicrosecondsPerExecution}us/execution over {measured.ExecutionCount} executions.");

      // No heap scan anywhere: every table under review is clustered and reached through it.
      Assert.DoesNotContain("PhysicalOp=\"Table Scan\"", measured.PlanXml, StringComparison.Ordinal);

      // AND NO SORT. The copy reads ORDER BY primary key and the validation walks both sides in that order;
      // if either needed an explicit Sort, a large tenant would spill to tempdb and the "streaming" claim
      // would be false. The clustered index already provides the order.
      Assert.False(measured.HasSort, $"{measured.Label} required an explicit Sort: {measured.Operation}");
    }
  }

  private sealed record MeasuredPlan(
    string Label,
    string PlanXml,
    long LogicalReadsPerExecution,
    long MicrosecondsPerExecution,
    long ExecutionCount)
  {
    // ALL operators and ALL indexes, not the first of each: the first PhysicalOp in a plan is often an outer
    // Compute Scalar or Top, and reporting that as "the operation" would describe the wrapper rather than
    // the access path under review.
    public string Operation => string.Join(" -> ", Values("PhysicalOp=\""));

    public string Index => Values("Index=\"") is { Count: > 0 } indexes
      ? string.Join(", ", indexes.Distinct(StringComparer.Ordinal))
      : "(none)";

    public bool HasSort => Values("PhysicalOp=\"").Contains("Sort", StringComparer.Ordinal);

    private List<string> Values(string marker)
    {
      var values = new List<string>();
      var cursor = 0;
      while (true)
      {
        var start = PlanXml.IndexOf(marker, cursor, StringComparison.Ordinal);
        if (start < 0)
        {
          return values;
        }

        start += marker.Length;
        var end = PlanXml.IndexOf('"', start);
        if (end < 0)
        {
          return values;
        }

        values.Add(PlanXml[start..end]);
        cursor = end;
      }
    }
  }


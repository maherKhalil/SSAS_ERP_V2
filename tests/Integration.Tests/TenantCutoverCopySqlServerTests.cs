  // ---- I. Two executors, one cutover. The database decides which one owns it.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task Only_one_instance_can_execute_a_cutover_copy_at_a_time()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await fixture.SeedCompaniesAsync(fixture.TenantA, 6, "OWN");
    var operationId = await fixture.BeginAndFreezeAsync();

    // Instance one, holding ownership exactly as a running copy does.
    await using var owner = new SqlConnection(fixture.PlatformConnectionString);
    await owner.OpenAsync();
    Assert.True(await TenantCutoverOperationLock.TryAcquireForSessionAsync(
      owner, operationId, TimeSpan.FromSeconds(5)));

    var contender = await fixture.CopyService().CopyAsync(operationId);

    Assert.True(contender.IsFailure);
    Assert.Equal(TenantStorageErrors.CutoverCopyOwnershipNotAcquired.Code, contender.Error.Code);
    Assert.Equal(0, await fixture.TargetCompanyCountAsync(fixture.TenantA));

    // OWNERSHIP IS TRANSIENT: dropping the connection — as a dying process would — releases it, and a retry
    // simply proceeds. No lease expiry, no stale-owner cleanup.
    await owner.CloseAsync();
    var resumed = await fixture.CopyService().CopyAsync(operationId);
    Assert.True(resumed.IsSuccess);
    Assert.Equal(6, await fixture.TargetCompanyCountAsync(fixture.TenantA));
  }

  // Two genuinely concurrent executors: whatever the interleaving, the target is exact and undoubled.

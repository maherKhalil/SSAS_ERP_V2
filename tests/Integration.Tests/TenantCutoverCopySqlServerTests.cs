  // ---- §15 TRIGGER REVIEW, read from the server rather than assumed.
  //
  // The tenant schema carries exactly one DML trigger, it is INSTEAD OF DELETE, and it is therefore not on
  // the copy's path — the copy only inserts. It is left ENABLED on the target throughout, so the target
  // inherits the same retention invariant the source has.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task The_only_tenant_trigger_is_a_delete_guard_that_the_copy_neither_fires_nor_disturbs()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await fixture.SeedCompaniesAsync(fixture.TenantA, 3, "TRG");
    var operationId = await fixture.BeginAndFreezeAsync();

    var before = await CopyFixture.TriggersAsync(fixture.TargetCatalog);
    var trigger = Assert.Single(before);
    Assert.Equal("TR_Companies_PreventDelete", trigger.Name);
    Assert.Contains("INSTEAD OF", trigger.Type, StringComparison.Ordinal);
    Assert.Contains("DELETE", trigger.Type, StringComparison.Ordinal);
    Assert.DoesNotContain("INSERT", trigger.Type, StringComparison.Ordinal);
    Assert.False(trigger.Disabled);

    Assert.True((await fixture.CopyService().CopyAsync(operationId)).IsSuccess);

    // Still exactly one trigger, still enabled: the copy did not disable it to make itself possible.
    var after = Assert.Single(await CopyFixture.TriggersAsync(fixture.TargetCatalog));
    Assert.Equal("TR_Companies_PreventDelete", after.Name);
    Assert.False(after.Disabled);

    // ...and it is live on the target, so the copied database refuses physical deletion exactly as the
    // source does. This is also what makes the engine's "never delete to make progress" rule unbreakable.
    var refused = await Assert.ThrowsAsync<SqlException>(() =>
      fixture.AttemptTargetDeleteAsync(fixture.TenantA));
    Assert.Contains("cannot be physically deleted", refused.Message, StringComparison.Ordinal);
  }


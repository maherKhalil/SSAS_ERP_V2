  // ---- A. The load-bearing test: one tenant moves, the other is untouched on both sides.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task Copying_one_tenant_moves_only_that_tenant_and_leaves_its_co_tenant_alone()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await fixture.SeedCompaniesAsync(fixture.TenantA, 3, "AAA");
    await fixture.SeedCompaniesAsync(fixture.TenantB, 2, "BBB");
    var operationId = await fixture.BeginAndFreezeAsync();

    var copied = await fixture.CopyService().CopyAsync(operationId);

    Assert.True(copied.IsSuccess);
    Assert.Equal(3, copied.Value.TotalRows);

    // SEVEN TENANT-OWNED TABLES as of FP-007 Phase 1. Branch joined Company in Branch foundation B0;
    // Employee and EmployeeBranchAssignment joined them once the copy plan was derived from the
    // CONTRIBUTOR-COMPOSED model rather than a contributor-free one; Department, DepartmentManager and
    // EmployeeDepartmentAssignment joined in turn. Only Company holds rows in this fixture, so TotalRows is
    // unchanged while the table count is not — and this count is precisely what would have stayed at two
    // while a promotion silently left every employee behind.
    Assert.Equal(7, copied.Value.TablesCopied);
    Assert.Equal(0, copied.Value.TablesAlreadyComplete);
    Assert.Equal(
      [
        nameof(Branch),
        nameof(Company),
        "Department",
        "DepartmentManager",
        "Employee",
        "EmployeeBranchAssignment",
        "EmployeeDepartmentAssignment"
      ],
      copied.Value.Tables.Select(table => table.EntityName).OrderBy(name => name, StringComparer.Ordinal));

    // TENANT A IS ON THE TARGET, AND ONLY TENANT A.
    Assert.Equal(3, await fixture.TargetCompanyCountAsync(fixture.TenantA));
    Assert.Equal(0, await fixture.TargetCompanyCountAsync(fixture.TenantB));
    Assert.Equal(3, await fixture.TargetCompanyCountAsync(null));

    // THE SHARED SOURCE IS UNCHANGED. A copy is not a move: nothing is deleted from the source, and the
    // co-tenant sharing the physical database is untouched.
    Assert.Equal(3, await fixture.SourceCompanyCountAsync(fixture.TenantA));
    Assert.Equal(2, await fixture.SourceCompanyCountAsync(fixture.TenantB));
  }

  // ---- C + D. Audit provenance verbatim; rowversion regenerated by the target.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task Audit_values_are_copied_verbatim_and_rowversion_is_target_generated()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await fixture.SeedCompaniesAsync(fixture.TenantA, 4, "AUD");
    var operationId = await fixture.BeginAndFreezeAsync();

    // ROWVERSION IS A PER-DATABASE COUNTER, so "source bytes != target bytes" is NOT a proof — two freshly
    // created databases can legitimately issue identical values, and an earlier version of this test failed
    // for exactly that reason rather than because anything was wrong.
    //
    // The deterministic proof is to push the TARGET's counter far past anything the source could hold, then
    // require every copied row's rowversion to sit above that watermark. A rowversion carried over from the
    // source would necessarily fall below it.
    await fixture.AdvanceTargetRowVersionCounterAsync();
    var watermark = await fixture.TargetRowVersionWatermarkAsync();

    var sourceRows = await CopyFixture.ReadCompaniesAsync(fixture.SourceCatalog, fixture.TenantA);
    Assert.All(sourceRows.Values, row => Assert.True(
      Counter(row.RowVersion) < watermark,
      "the source counter is not below the target watermark, so this test would prove nothing"));

    Assert.True((await fixture.CopyService().CopyAsync(operationId)).IsSuccess);
    var targetRows = await CopyFixture.ReadCompaniesAsync(fixture.TargetCatalog, fixture.TenantA);

    Assert.Equal(sourceRows.Count, targetRows.Count);
    foreach (var (key, source) in sourceRows)
    {
      var target = targetRows[key];

      // VERBATIM. Not "recent", not "re-stamped by the copy" — the same provenance the source recorded.
      Assert.Equal(source.CreatedUtc, target.CreatedUtc);
      Assert.Equal(source.CreatedBy, target.CreatedBy);
      Assert.Equal(source.ModifiedUtc, target.ModifiedUtc);
      Assert.Equal(source.ModifiedBy, target.ModifiedBy);
      Assert.Equal(source.StatusChangedUtc, target.StatusChangedUtc);
      Assert.Equal(source.StatusChangedBy, target.StatusChangedBy);
      Assert.Equal(source.TenantId, target.TenantId);
      Assert.Equal(source.CompanyCode, target.CompanyCode);

      // ROWVERSION IS THE TARGET'S OWN, issued by the target's counter during this copy.
      Assert.NotNull(target.RowVersion);
      Assert.NotEmpty(target.RowVersion!);
      Assert.True(
        Counter(target.RowVersion) > watermark,
        "the target rowversion predates the copy, so it was not generated by the target");
    }
  }

  // rowversion is an 8-byte big-endian database counter.
  private static ulong Counter(byte[] rowVersion) =>
    System.Buffers.Binary.BinaryPrimitives.ReadUInt64BigEndian(rowVersion);

  // ---- H. Retry after a completed table: re-validated, skipped, not duplicated.
  [Fact]
  [Trait("Decision", "ADR-020")]
  public async Task A_retry_revalidates_completed_tables_and_never_duplicates_them()
  {
    await using var fixture = await CopyFixture.CreateAsync();
    await fixture.SeedCompaniesAsync(fixture.TenantA, 5, "RTY");
    var operationId = await fixture.BeginAndFreezeAsync();

    var first = await fixture.CopyService().CopyAsync(operationId);
    Assert.True(first.IsSuccess);
    // The whole tenant-owned manifest: Branch and Company, plus the two HR tables the contributor-composed
    // model added in FP-006C6 and the three FP-007 Phase 1 added.
    Assert.Equal(7, first.Value.TablesCopied);

    // The retry a dead process's replacement would perform.
    var second = await fixture.CopyService().CopyAsync(operationId);

    Assert.True(second.IsSuccess);

    // COMPANY IS RECOGNISED AS ALREADY COMPLETE. The six empty tables are not, and that is correct rather
    // than a gap: an empty table is indistinguishable from one that was never copied, so the engine copies
    // each again, moving nothing. The retry's safety claim is about not DUPLICATING rows, which the counts
    // below still prove exactly.
    Assert.Equal(6, second.Value.TablesCopied);
    Assert.Equal(1, second.Value.TablesAlreadyComplete);
    Assert.Equal(5, second.Value.TotalRows);

    // Skipping is proven by the row count, not only by the report: a second insert would have doubled it.
    Assert.Equal(5, await fixture.TargetCompanyCountAsync(fixture.TenantA));
  }


    // §15: the complete DML trigger inventory of the tenant schema, read from the server.
    public static async Task<List<(string Name, string Type, bool Disabled)>> TriggersAsync(string catalog)
    {
      await using var connection = new SqlConnection(ConnectionFor(catalog));
      await connection.OpenAsync();
      await using var command = connection.CreateCommand();
      command.CommandText = """
        SELECT t.[name],
               CASE WHEN t.[is_instead_of_trigger] = 1 THEN N'INSTEAD OF' ELSE N'AFTER' END + N' ' +
                 STUFF((SELECT N',' + te.[type_desc] FROM sys.trigger_events te
                        WHERE te.[object_id] = t.[object_id] FOR XML PATH('')), 1, 1, N''),
               t.[is_disabled]
        FROM sys.triggers t
        JOIN sys.objects o ON o.[object_id] = t.[parent_id]
        JOIN sys.schemas s ON s.[schema_id] = o.[schema_id]
        WHERE s.[name] = N'tenant'
        ORDER BY t.[name];
        """;

      var triggers = new List<(string, string, bool)>();
      await using var reader = await command.ExecuteReaderAsync();
      while (await reader.ReadAsync())
      {
        triggers.Add((reader.GetString(0), reader.GetString(1), reader.GetBoolean(2)));
      }

      return triggers;
    }

